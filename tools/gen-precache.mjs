#!/usr/bin/env node
/**
 * Writes src/precache-list.js: every app file (index.html, manifest, icons, src/, vendor/),
 * the app version from package.json and a content hash of all those files (DEF-08), so any
 * code change gives a new cache name and the installed app sees an update.
 * Runs automatically in the GitHub Pages workflow; run it locally after changing files:
 *   node tools/gen-precache.mjs
 */
import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const OUT = 'src/precache-list.js';

function walk(dir) {
  return readdirSync(join(root, dir)).flatMap((name) => {
    const rel = join(dir, name);
    return statSync(join(root, rel)).isDirectory() ? walk(rel) : [rel.split(sep).join('/')];
  });
}

/** @returns {string[]} relative app file paths ("./…") */
export function appFiles() {
  return ['index.html', 'manifest.webmanifest', ...walk('icons'), ...walk('src'), ...walk('vendor')]
    .filter((f) => !/(^|\/)\./.test(f))
    .map((f) => `./${f}`)
    .sort();
}

/** @returns {string} 12-hex-digit SHA-256 over the paths and bytes of all precached files */
export function buildHash() {
  const h = createHash('sha256');
  for (const f of appFiles()) {
    if (f === `./${OUT}`) continue;
    h.update(f);
    h.update(readFileSync(join(root, f.slice(2))));
  }
  return h.digest('hex').slice(0, 12);
}

if (process.argv[1] && relative(process.argv[1], fileURLToPath(import.meta.url)) === '') {
  const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
  const files = ['./', ...appFiles()];
  const build = buildHash();
  const body = `/* Generated by tools/gen-precache.mjs — do not edit. Loaded by sw.js via importScripts. */\nself.S2P_APP_VERSION = ${JSON.stringify(version)};\nself.S2P_BUILD = ${JSON.stringify(build)};\nself.S2P_PRECACHE = ${JSON.stringify(files, null, 2)};\n`;
  writeFileSync(join(root, OUT), body);
  console.log(`${OUT}: ${files.length} entries, version ${version}, build ${build}`);
}
