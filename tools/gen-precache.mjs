#!/usr/bin/env node
/**
 * Writes src/precache-list.js: every app file (index.html, manifest, icons, src/, vendor/)
 * plus the app version from package.json. Run after adding/removing files:
 *   node tools/gen-precache.mjs
 */
import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const OUT = 'src/precache-list.js';

function walk(dir) {
  return readdirSync(join(root, dir)).flatMap((name) => {
    const rel = join(dir, name);
    return statSync(join(root, rel)).isDirectory() ? walk(rel) : [rel.split(sep).join('/')];
  });
}

/** @returns {string[]} relative app file paths ("./…") */
export function appFiles() {
  return ['index.html', 'manifest.webmanifest', ...walk('icons'), ...walk('src'), ...walk('vendor')]
    .filter((f) => !/(^|\/)\./.test(f))
    .map((f) => `./${f}`)
    .sort();
}

if (process.argv[1] && relative(process.argv[1], fileURLToPath(import.meta.url)) === '') {
  const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
  const files = ['./', ...appFiles()];
  const body = `/* Generated by tools/gen-precache.mjs — do not edit. Loaded by sw.js via importScripts. */\nself.S2P_APP_VERSION = ${JSON.stringify(version)};\nself.S2P_PRECACHE = ${JSON.stringify(files, null, 2)};\n`;
  writeFileSync(join(root, OUT), body);
  console.log(`${OUT}: ${files.length} entries, version ${version}`);
}
